bool X11VulkanWindow::open(const WindowConfig& config) {
    width_  = config.width;
    height_ = config.height;

    display_ = XOpenDisplay(nullptr);
    if (!display_) return false;

    int screen = DefaultScreen(display_);
    xwindow_   = XCreateSimpleWindow(
        display_, RootWindow(display_, screen),
        0, 0, width_, height_, 0,
        BlackPixel(display_, screen),
        BlackPixel(display_, screen));

    XStoreName(display_, static_cast<::Window>(xwindow_), config.title.c_str());
    XSelectInput(display_, static_cast<::Window>(xwindow_),
                 ExposureMask | KeyPressMask | StructureNotifyMask |
                 ButtonPressMask | ButtonReleaseMask | PointerMotionMask);
    XMapWindow(display_, static_cast<::Window>(xwindow_));

    canvas_ = std::make_unique<VulkanCanvas>();
    if (!canvas_->init(display_, xwindow_, width_, height_)) return false;

    open_ = true;
    return true;
}

bool X11VulkanWindow::pollEvents() {
    while (XPending(display_)) {
        XEvent ev;
        XNextEvent(display_, &ev);
        if (ev.type == DestroyNotify || ev.type == ClientMessage) {
            open_ = false;
            return false;
        }
    }
    return open_;
}

bool X11VulkanWindow::isOpen() const { return open_; }

void X11VulkanWindow::present() { /* endFrame() already called present */ }

void X11VulkanWindow::close() {
    if (!open_) return;
    canvas_->shutdown();
    XDestroyWindow(display_, static_cast<::Window>(xwindow_));
    XCloseDisplay(display_);
    display_ = nullptr;
    xwindow_ = 0;
    open_    = false;
}

X11VulkanWindow::~X11VulkanWindow() { close(); }

