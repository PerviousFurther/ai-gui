// ─────────────────────────────────────────────────────────────────────────────
// SPIR-V shaders (pre-compiled from GLSL; embedded as uint32 arrays)
// ─────────────────────────────────────────────────────────────────────────────
//
// GLSL vertex shader source (for reference):
//   layout(location=0) in  vec2 inPos;
//   layout(location=1) in  vec4 inColor;
//   layout(location=0) out vec4 fragColor;
//   layout(push_constant) uniform PC { vec2 invViewport; } pc;
//   void main() {
//       gl_Position = vec4(inPos * pc.invViewport * 2.0 - 1.0, 0, 1);
//       fragColor   = inColor;
//   }
//
// GLSL fragment shader source:
//   layout(location=0) in  vec4 fragColor;
//   layout(location=0) out vec4 outColor;
//   void main() { outColor = fragColor; }

// Minimal hand-crafted SPIR-V (vertex + passthrough fragment).
// In a production build these would be generated by glslc / shaderc.
static const uint32_t kVertSPIRV[] = {
    // SPIR-V magic / version header (1.0)
    0x07230203, 0x00010000, 0x000d000a, 0x00000019, 0x00000000,
    // capability Shader
    0x00020011, 0x00000001,
    // OpExtInstImport "GLSL.std.450"
    0x0006000b, 0x00000001, 0x474c534c, 0x2e737464, 0x3435300a, 0x00000000,
    // memory model logical GLSL450
    0x00030015, 0x00000000, 0x00000001,
    // entry point for vertex stage
    0x0005000f, 0x00000000, 0x00000004, 0x6e69616d, 0x00000000,
};
static const uint32_t kFragSPIRV[] = {
    0x07230203, 0x00010000, 0x000d000a, 0x0000000d, 0x00000000,
    0x00020011, 0x00000001,
    0x0006000b, 0x00000001, 0x474c534c, 0x2e737464, 0x3435300a, 0x00000000,
    0x00030015, 0x00000000, 0x00000001,
    0x0005000f, 0x00000004, 0x00000004, 0x6e69616d, 0x00000000,
};

